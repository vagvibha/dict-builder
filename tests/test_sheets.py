"""Tests for sheets.py / plan.py sync-sheets (Sheets API replaced by a fake)."""
import tempfile
import unittest
from pathlib import Path

from tests.helpers import write
from errors import DictionaryBuildError
import sheets
import plan


def sync_sheets(ws, content, client):
    return plan.sync_sheets(ws, content, client, log=lambda m: None)

URL = "https://docs.google.com/spreadsheets/d/SID/edit?gid={gid}#gid={gid}"
TABLE = [["title", "T", "keys", "Words", "entry", "Entry", ""],
         ["Words", "Entry", "", ""],
         ["कृ", " to do ", "", ""],
         ["", "", "", ""]]


class FakeClient:
    """tabs: {gid: rows or exception}; tab names are 'Tab<gid>'."""

    def __init__(self, tabs):
        self.tabs, self.calls = tabs, []

    def fetch(self, url, tab=None):
        self.calls.append(url)
        _, gid = sheets.parse_url(url)
        title = sheets.resolve_tab({g: f"Tab{g}" for g in self.tabs}, gid, tab)
        value = self.tabs[int(title[3:])]
        if isinstance(value, Exception):
            raise value
        return value, title


class _Ws(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.ws = Path(self._tmp.name)
        self.content = self.ws / "contents"

    def tearDown(self):
        self._tmp.cleanup()

    def config(self, sheets_yaml):
        write(self.content / "meta.yaml", "dictionaries: [misc]\n" + sheets_yaml)

    def entry(self, path, gid, extra=""):
        return f"  - path: {path}\n    url: '{URL.format(gid=gid)}'\n{extra}"


class TestHelpers(unittest.TestCase):
    def test_parse_url(self):
        self.assertEqual(sheets.parse_url(URL.format(gid=7)), ("SID", 7))
        self.assertEqual(sheets.parse_url("https://docs.google.com/spreadsheets/d/SID/edit"),
                         ("SID", None))
        self.assertIsNone(sheets.parse_url("https://example.com/x"))

    def test_resolve_tab(self):
        titles = {0: "Words", 7: "Other"}
        self.assertEqual(sheets.resolve_tab(titles, 7, None), "Other")
        self.assertEqual(sheets.resolve_tab(titles, 7, "Other"), "Other")
        self.assertEqual(sheets.resolve_tab(titles, None, "Words"), "Words")
        for gid, tab, msg in ((9, None, "no tab with gid=9"),
                              (7, "Words", "named 'Other', but the config says 'tab: Words'"),
                              (None, "Nope", "no tab named 'Nope'")):
            with self.subTest(gid=gid, tab=tab):
                with self.assertRaises(DictionaryBuildError) as ctx:
                    sheets.resolve_tab(titles, gid, tab)
                self.assertIn(msg, str(ctx.exception))

    def test_tidy(self):
        self.assertEqual(sheets.tidy(TABLE),
                         [["title", "T", "keys", "Words", "entry", "Entry"],
                          ["Words", "Entry", "", "", "", ""],
                          ["कृ", "to do", "", "", "", ""]])
        # NFC: e + combining acute -> one character
        self.assertEqual(sheets.tidy([["e\u0301"]]), [["\u00e9"]])
        self.assertEqual(sheets.tidy([[" a\r\nb\u00a0c\n "]]), [["a\nb c"]])
        self.assertEqual(sheets.tidy([]), [])

    def test_to_record_text(self):
        self.assertEqual(sheets.to_record_text(TABLE, "U", "Words"), (
            "# GENERATED by `plan.py sync-sheets` from Google Sheets. Do not edit:\n"
            "# every sync overwrites this file. Edit the sheet instead.\n"
            "# Sheet: U\n# Tab: Words\n"
            "HEADER:type=record\nHEADER:title=T\nHEADER:keys=Words\nHEADER:entry=Entry\n"
            "\n.--- कृ\n.Words: कृ\n.Entry: to do\n"))


class TestConfig(_Ws):
    def load(self, text):
        import yaml
        return sheets.load_sheets_config(yaml.safe_load(text), self.ws, self.ws / "m.yaml",
                                         self.content)

    def test_ok(self):
        out = self.load("- {path: contents/a/x.txt, url: '" + URL.format(gid=1) + "'}\n"
                        "- {path: contents/b/y.txt, url: '" + URL.format(gid=2) + "', fetch: false}\n"
                        "- {path: contents/z.txt, url: 'https://docs.google.com/spreadsheets/d/S/edit', "
                        "tab: Words}\n")
        self.assertEqual([(s["rel"], s["tab"], s["fetch"]) for s in out],
                         [("contents/a/x.txt", None, True), ("contents/b/y.txt", None, False),
                          ("contents/z.txt", "Words", True)])
        self.assertEqual(out[0]["path"], (self.ws / "contents/a/x.txt").resolve())

    def test_errors(self):
        u = URL.format(gid=1)
        cases = {
            "csv": f"- {{path: contents/a.csv, url: '{u}'}}\n",
            "outside contents": f"- {{path: masters/a.txt, url: '{u}'}}\n",
            "outside": f"- {{path: ../a.txt, url: '{u}'}}\n",
            "absolute": f"- {{path: /tmp/a.txt, url: '{u}'}}\n",
            "no gid or tab": "- {path: contents/a.txt, url: 'https://docs.google.com/spreadsheets/d/S/edit'}\n",
            "not a sheet": "- {path: contents/a.txt, url: 'https://example.com/x', tab: T}\n",
            "empty tab": f"- {{path: contents/a.txt, url: '{u}', tab: ''}}\n",
            "unknown key": f"- {{path: contents/a.txt, url: '{u}', sheet: x}}\n",
            "dup": f"- {{path: contents/a.txt, url: '{u}'}}\n- {{path: ./contents/a.txt, url: '{u}'}}\n",
            "bad fetch": f"- {{path: contents/a.txt, url: '{u}', fetch: 'no'}}\n",
            "not list": "a: 1\n",
        }
        for label, text in cases.items():
            with self.subTest(label):
                with self.assertRaises(DictionaryBuildError):
                    self.load(text)


class TestSync(_Ws):
    def test_writes_record_files_and_reports_same(self):
        self.config("sheets:\n" + self.entry("contents/misc/w.txt", 1)
                    + self.entry("contents/misc/sub/v.txt", 2))
        client = FakeClient({1: TABLE, 2: TABLE})
        written = sync_sheets(self.ws, self.content, client)
        self.assertEqual(sorted(p.name for p in written), ["v.txt", "w.txt"])
        self.assertEqual((self.content / "misc/w.txt").read_text(encoding="utf-8"),
                         sheets.to_record_text(TABLE, URL.format(gid=1), "Tab1"))
        # unchanged second time: nothing written
        self.assertEqual(sync_sheets(self.ws, self.content, client), [])

    def test_tab_names(self):
        self.config("sheets:\n" + self.entry("contents/misc/w.txt", 1, "    tab: Tab1\n")
                    + "  - path: contents/misc/v.txt\n"
                      "    url: https://docs.google.com/spreadsheets/d/SID/edit\n"
                      "    tab: Tab2\n")
        logs = []
        plan.sync_sheets(self.ws, self.content, FakeClient({1: TABLE, 2: TABLE}),
                         log=logs.append)
        self.assertEqual(logs, ["updated  contents/misc/w.txt (tab 'Tab1', 1 entries)",
                                "updated  contents/misc/v.txt (tab 'Tab2', 1 entries)"])
        # renamed in the config (or the sheet): the sync fails, nothing written
        self.config("sheets:\n" + self.entry("contents/misc/w.txt", 1, "    tab: Renamed\n"))
        with self.assertRaises(DictionaryBuildError) as ctx:
            sync_sheets(self.ws, self.content, FakeClient({1: TABLE}))
        self.assertIn("named 'Tab1', but the config says 'tab: Renamed'", str(ctx.exception))

    def test_all_or_nothing(self):
        self.config("sheets:\n" + self.entry("contents/misc/a.txt", 1)
                    + self.entry("contents/misc/b.txt", 2))
        client = FakeClient({1: TABLE, 2: RuntimeError("HTTP 500")})
        with self.assertRaises(DictionaryBuildError) as ctx:
            sync_sheets(self.ws, self.content, client)
        self.assertIn("b.txt: RuntimeError: HTTP 500", str(ctx.exception))
        self.assertFalse((self.content / "misc/a.txt").exists())

    def test_sheet_problems(self):
        self.config("sheets:\n" + self.entry("contents/misc/a.txt", 1)
                    + self.entry("contents/misc/b.txt", 2))
        bad_meta = [["Words", "Entry"], ["कृ", "x"]]          # header row in row 1
        bad_rows = TABLE[:2] + [["k", "x\n.y"], ["j", "#N/A"]]
        with self.assertRaises(DictionaryBuildError) as ctx:
            sync_sheets(self.ws, self.content, FakeClient({1: bad_meta, 2: bad_rows}))
        msg = str(ctx.exception)
        self.assertIn("contents/misc/a.txt: row 1 (metadata), column A: unsupported key 'Words'",
                      msg)
        self.assertIn("contents/misc/b.txt: problems in the sheet:", msg)
        self.assertIn("row 3, column B (Entry): line 2 of the cell starts with '.'", msg)
        self.assertIn("row 4: column 'Entry' shows a spreadsheet error '#N/A'", msg)

    def test_fetch_false_keeps_file(self):
        write(self.content / "misc/a.txt", "old, broken\n")
        self.config("sheets:\n" + self.entry("contents/misc/a.txt", 1, "    fetch: false\n")
                    + self.entry("contents/misc/b.txt", 2))
        client = FakeClient({2: TABLE})
        sync_sheets(self.ws, self.content, client)
        self.assertEqual(client.calls, [URL.format(gid=2)])
        self.assertEqual((self.content / "misc/a.txt").read_text(), "old, broken\n")

    def test_empty_tab_and_no_config(self):
        self.config("")
        self.assertEqual(sync_sheets(self.ws, self.content, FakeClient({})), [])
        self.config("sheets:\n" + self.entry("contents/a.txt", 1))
        with self.assertRaises(DictionaryBuildError) as ctx:
            sync_sheets(self.ws, self.content, FakeClient({1: [["", ""]]}))
        self.assertIn("the tab is empty", str(ctx.exception))


class TestClientCredentials(unittest.TestCase):
    def test_no_credentials(self):
        import os
        saved = {k: os.environ.pop(k, None)
                 for k in ("GOOGLE_SERVICE_ACCOUNT_JSON", "GOOGLE_APPLICATION_CREDENTIALS")}
        try:
            with self.assertRaises(DictionaryBuildError) as ctx:
                sheets.SheetsClient()
            self.assertRegex(str(ctx.exception), "no credentials|missing libraries")
        finally:
            os.environ.update({k: v for k, v in saved.items() if v is not None})


